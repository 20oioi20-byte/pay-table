const { chromium } = require('playwright');
(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport:{ width:1480, height:950 }, deviceScaleFactor:1.25, acceptDownloads:true });
await p.route('**/xlsx.full.min.js', r => r.fulfill({ path: process.argv[3] }));
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('file://' + __dirname + '/stats_prototype.html'); await p.waitForTimeout(400);
await p.screenshot({ path: __dirname + '/s6_1_all.png', fullPage:true });
await p.click('#tree .row[data-ind="금융"] .cb'); await p.waitForTimeout(200);
await p.screenshot({ path: __dirname + '/s6_2_finance.png', fullPage:true });
await p.click('text=전체 해제'); await p.click('#tree .row[data-sub="보험"]'); await p.waitForTimeout(200);
await p.click('#colBtn'); await p.waitForTimeout(100);
await p.screenshot({ path: __dirname + '/s6_3_insurance.png', fullPage:true });
await p.mouse.click(5,5);
await p.click('#tabs button[data-t="pivot"]'); await p.waitForTimeout(150);
await p.screenshot({ path: __dirname + '/s6_4_pivot.png', fullPage:true });
await p.click('#tabs button[data-t="heat"]'); await p.click('#tabs button[data-t="list"]');
await p.click('#list th[data-sort="yoy"]');
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#xls')]); await dl.saveAs(process.argv[2]);
const [dl2] = await Promise.all([p.waitForEvent('download'), p.click('#csv')]); await dl2.saveAs(process.argv[2] + '.csv');
console.log('errors', errs); await b.close(); })();
