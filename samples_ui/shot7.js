const { chromium } = require('playwright');
(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport:{ width:1480, height:950 }, deviceScaleFactor:1.25, acceptDownloads:true });
await p.route('**/xlsx.full.min.js', r => r.fulfill({ path: process.argv[3] }));
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('file://' + __dirname + '/stats_prototype.html'); await p.waitForTimeout(300);
await p.screenshot({ path: __dirname + '/s9_1_all.png', fullPage:true });
await p.click('#grid .sr2[data-pick="보험"]'); await p.waitForTimeout(150);
await p.click('#tabs button[data-t="list"]'); await p.waitForTimeout(150);
await p.screenshot({ path: __dirname + '/s9_2_insurance.png', fullPage:true });
await p.click('#job button[data-j="관리자"]'); await p.click('#unit button[data-u="m"]'); await p.waitForTimeout(150);
await p.screenshot({ path: __dirname + '/s9_3_manager_month.png', clip:{ x:0, y:0, width:1480, height:760 } });
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#xls')]); await dl.saveAs(process.argv[2]);
console.log('errors', errs); await b.close(); })();
